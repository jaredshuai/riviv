function Find-OwnDialogs($procId) {
    # All top-level #32770 windows of OUR process (FindWindowW alone could
    # hit another process's dialog, so enumerate and filter by pid).
    $script:topHits = @()
    $cb = [S178+EnumProc]{ param($h, $lp) $script:topHits += $h; return $true }
    [void][S178]::EnumWindows($cb, [IntPtr]::Zero)
    $found = @()
    foreach ($h in $script:topHits) {
        if ((Get-Class $h) -eq '#32770') {
            $wpid = 0
            [void][S178]::GetWindowThreadProcessId($h, [ref]$wpid)
            if ($wpid -eq $procId) { $found += $h }
        }
    }
    $script:topHits = $null
    return ,$found
}

function Invoke-ConfirmYes($procId, $gonePath, $ms) {
    # The delete-confirm ladder: poll for a #32770 of our pid that carries a
    # Yes button (GetDlgItem id 6 = IDYES), BM_CLICK it, wait for the dialog
    # to go. If no dialog ever appears but the target file vanishes anyway,
    # classify as AutoNoDialog (delete confirmations disabled on this
    # machine) instead of burning the full $ms. Unexpected shapes get a
    # child-control dump for honest attribution.
    $dlg = [IntPtr]::Zero
    $anyDlg = [IntPtr]::Zero
    $deadline = [DateTime]::UtcNow.AddMilliseconds($ms)
    while ([DateTime]::UtcNow -lt $deadline) {
        foreach ($d in (Find-OwnDialogs $procId)) {
            if ($anyDlg -eq [IntPtr]::Zero) { $anyDlg = $d }
            if ([S178]::GetDlgItem($d, 6) -ne [IntPtr]::Zero) { $dlg = $d; break }
        }
        if ($dlg -ne [IntPtr]::Zero) { break }
        if (-not (Test-Path $gonePath)) { break }
        Start-Sleep -Milliseconds 100
    }
    $res = @{ Dlg = $dlg; YesClicked = $false; Gone = $false; AutoNoDialog = $false; AnyDlg = $anyDlg; Children = '' }
    if ($dlg -ne [IntPtr]::Zero) {
        $yes = [S178]::GetDlgItem($dlg, 6)
        [void][S178]::PostMessage($yes, 0x00F5, [IntPtr]::Zero, [IntPtr]::Zero)   # BM_CLICK
        $res.YesClicked = $true
        if (Wait-DialogGone $dlg 6000) {
            $res.Gone = $true
        } else {
            Write-Host '  [dialog] first BM_CLICK on Yes did not dismiss it, retrying once'
            [void][S178]::PostMessage($yes, 0x00F5, [IntPtr]::Zero, [IntPtr]::Zero)
            if (Wait-DialogGone $dlg 4000) { $res.Gone = $true }
            else { $res.Children = [S178]::ChildrenDump($dlg) }
        }
    } else {
        if ($anyDlg -ne [IntPtr]::Zero) { $res.Children = [S178]::ChildrenDump($anyDlg) }
        if (Test-Path $gonePath) { } else { $res.AutoNoDialog = $true }
    }
    return $res
}
function Menu-State122($main) {
    # PostMessage WM_INITMENU (the app refreshes its BAR menu on it -
    # src/window.rs on_initmenu over GetMenu(hwnd), the wParam is ignored),
    # then read command 122's state MF_BYCOMMAND. 0xFFFFFFFF = no menu or
    # item absent. Each poll re-posts the (idempotent) refresh.
    [void][S178]::PostMessage($main, 0x0116, [IntPtr]::Zero, [IntPtr]::Zero)   # WM_INITMENU
    Start-Sleep -Milliseconds 200
    $bar = [S178]::GetMenu($main)
    if ($bar -eq [IntPtr]::Zero) { return [uint32]4294967295 }
    return [S178]::GetMenuState($bar, [uint32]122, [uint32]0)
}
function Wait-Menu122Grayed($main, $ms) {
    $ok = Wait-Until { $s = Menu-State122 $main; (($s -ne [uint32]4294967295) -and (($s -band [uint32]1) -ne 0)) } $ms
    return @{ Ok = $ok; State = (Menu-State122 $main) }
}
function Wait-Menu122Enabled($main, $ms) {
    $ok = Wait-Until { $s = Menu-State122 $main; (($s -ne [uint32]4294967295) -and (($s -band [uint32]1) -eq 0)) } $ms
    return @{ Ok = $ok; State = (Menu-State122 $main) }
}


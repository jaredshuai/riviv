# default DateModified-descending nav order is a, b, c).
#
# Command ids (src/menu.rs, unit-tested there): FileDeleteRecycle=13,
# FileDeletePermanently=14, NavNext=107, NavPrev=108, EditUndoDelete=122.
# Both delete commands surface the SHELL's own confirm dialog (class
# #32770; the Yes button carries control id IDYES = 6). Undo semantics
# (src/window.rs undo_delete_current / delete_current, src/filemgmt.rs

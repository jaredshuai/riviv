function Wait-Exit($p, $ms) {
    # Exit code via GetExitCodeProcess on the handle captured while alive.
    if ($p.WaitForExit($ms)) {
        $code = 0
        [void][S178]::GetExitCodeProcess($p.Handle, [ref]$code)
        return $code
    }
    return $null
}
function Hash-Of($path) {
    # Shared-read hash (riviv may still hold the file when polled).
    for ($i = 0; $i -lt 10; $i++) {
        try {
            if (-not (Test-Path $path)) { return '(absent)' }
            $fs = [IO.File]::Open($path, [IO.FileMode]::Open, [IO.FileAccess]::Read, [IO.FileShare]::ReadWrite)
            try {
                $sha = [System.Security.Cryptography.SHA256]::Create()
                $h = $sha.ComputeHash($fs)
                return ([BitConverter]::ToString($h)).Replace('-', '').ToLower()
            } finally { $fs.Dispose() }
        } catch { Start-Sleep -Milliseconds 100 }
    }
    return '(unreadable)'
}
function Wait-FileState($path, $wantExists, $ms) {
